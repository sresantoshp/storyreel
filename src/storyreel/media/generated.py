"""Register generated media (TTS, procedural sound) as project assets and place them.

Generated files live in `<project>/assets/generated/` (they are pinned project content,
not cache). Each asset row records `is_generated = 1`, the licence of what made it, and a
`source_url` describing the generator and its parameters.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

from storyreel.errors import StoryReelError
from storyreel.media.importer import import_files
from storyreel.project import store
from storyreel.project.edits import Editor
from storyreel.timebase import FLICKS, seconds_to_flicks

PROCEDURAL_LICENSE = "procedural (generated by StoryReel), CC0"


def generated_dir(project: store.Project) -> Path:
    d = project.root / "assets" / "generated"
    d.mkdir(parents=True, exist_ok=True)
    return d


def generated_name(prefix: str, params: dict[str, Any], suffix: str = ".wav") -> str:
    """Stable file name for a generator call: same parameters -> same file (reused)."""
    key = hashlib.blake2b(
        json.dumps(params, sort_keys=True, ensure_ascii=False).encode("utf-8"), digest_size=8
    ).hexdigest()
    return f"{prefix}_{key}{suffix}"


def import_generated(
    project: store.Project,
    path: Path,
    *,
    ffmpeg: Path,
    ffprobe: Path,
    license: str,
    source: str,
    tags: str = "",
) -> int:
    """Import `path` as a generated asset and return its asset id.

    Proxies (waveform peaks) are built as for any import. Re-importing the same file
    returns the existing id and refreshes its licence/source fields.
    """
    results = import_files(project, [path], ffmpeg=ffmpeg, ffprobe=ffprobe)
    r = results[0]
    if r.asset_id is None or r.status == "skipped":
        raise StoryReelError(
            f"The generated file {path.name} could not be imported: {r.message}",
            fix="Delete it and generate it again.",
        )
    project.con.execute(
        "UPDATE asset SET is_generated = 1, license = ?, source_url = ?, tags = ? WHERE id = ?",
        (license, source, tags, r.asset_id),
    )
    return r.asset_id


def _overlaps(project: store.Project, track_id: int, start: int, duration: int) -> bool:
    row = project.con.execute(
        "SELECT 1 FROM clip WHERE track_id = ? AND start < ? AND start + duration > ? LIMIT 1",
        (track_id, start + duration, start),
    ).fetchone()
    return row is not None


def track_end(project: store.Project, bus: str) -> int:
    """End (flicks) of the last clip on any audio track routed to `bus`; 0 if none."""
    row = project.con.execute(
        "SELECT coalesce(max(c.start + c.duration), 0) FROM clip c "
        "JOIN track t ON t.id = c.track_id WHERE t.kind = 'audio' AND t.bus = ?",
        (bus,),
    ).fetchone()
    return int(row[0])


def free_audio_track(
    project: store.Project, ed: Editor, bus: str, start: int, duration: int
) -> int:
    """First audio track on `bus` with room at [start, start+duration); adds one if needed."""
    for row in project.con.execute(
        "SELECT id FROM track WHERE kind = 'audio' AND bus = ? ORDER BY idx", (bus,)
    ).fetchall():
        if not _overlaps(project, int(row["id"]), start, duration):
            return int(row["id"])
    tid = ed.add_track("audio")
    if bus != "dialogue":  # new tracks default to the dialogue bus
        ed.set_track(tid, bus=bus)
    return tid


def place_audio(
    project: store.Project, asset_id: int, *, bus: str, at: float | None, gain_db: float = 0.0
) -> tuple[int, int, int]:
    """Put the whole asset on a free audio track of `bus`. Returns (clip_id, start, duration)
    in flicks. `at=None` appends after the bus's last clip. Start and length are snapped to
    the frame grid (length rounded down, so it never needs more source than exists)."""
    asset = project.con.execute("SELECT * FROM asset WHERE id = ?", (asset_id,)).fetchone()
    if asset is None or not asset["duration"]:
        raise StoryReelError(f"Asset {asset_id} has no audio duration.")
    rate = project.settings().rate
    start = seconds_to_flicks(at) if at is not None else track_end(project, bus)
    start = rate.frame_to_flicks(rate.flicks_to_frame(start))
    frames = int(asset["duration"]) * rate.num // (rate.den * FLICKS)
    if frames < 1:
        raise StoryReelError("The generated sound is shorter than one video frame.")
    duration = rate.frame_to_flicks(frames)
    while duration > int(asset["duration"]) and frames > 1:  # rounding guard
        frames -= 1
        duration = rate.frame_to_flicks(frames)
    ed = Editor(project.con)
    tid = free_audio_track(project, ed, bus, start, duration)
    cid = ed.add_clip(tid, start, duration, asset_id=asset_id, gain_db=gain_db)
    return cid, start, duration
